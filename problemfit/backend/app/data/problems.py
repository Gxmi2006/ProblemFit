def _context_title(context: str) -> str:
    return " ".join(word.capitalize() for word in context.split())


def _generated_problem(family: dict[str, Any], serial: int, context: str) -> dict[str, Any]:
    return {
        "id": f"pf-gen-{serial:03d}",
        "title": f"{family['title'].format(context_title=_context_title(context))} Set {serial}",
        "difficulty": family["difficulty"],
        "required_topics": family["required_topics"],
        "prerequisite_topics": family["prerequisite_topics"],
        "focus": family["focus"].format(context=context),
        "sample_input": family["sample_input"],
        "sample_output": family["sample_output"],
    }


def _expanded_blueprints() -> list[dict[str, Any]]:
    blueprints = list(PROBLEM_BLUEPRINTS)
    counts = Counter(problem["difficulty"] for problem in blueprints)
    serial = 81
    families_by_difficulty: dict[str, list[dict[str, Any]]] = {}
    for family in EXTRA_PROBLEM_FAMILIES:
        families_by_difficulty.setdefault(family["difficulty"], []).append(family)

    for difficulty, target_count in TARGET_DIFFICULTY_COUNTS.items():
        families = families_by_difficulty[difficulty]
        while counts[difficulty] < target_count:
            generated_index = counts[difficulty] - Counter(problem["difficulty"] for problem in PROBLEM_BLUEPRINTS)[difficulty]
            family = families[generated_index % len(families)]
            context = EXTRA_CONTEXTS[(generated_index + len(difficulty)) % len(EXTRA_CONTEXTS)]
            blueprints.append(_generated_problem(family, serial, context))
            serial += 1
            counts[difficulty] += 1
    return blueprints


def _input_format(problem: dict[str, Any]) -> str:
    topics = set(problem["required_topics"])
    if "graphs" in topics or "trees" in topics:
        return "First line contains node/grid sizes, followed by edges or grid rows described in the statement."
    if "strings" in topics and "arrays" not in topics:
        return "One or more strings as described in the statement."
    if "queues" in topics or "stacks" in topics:
        return "A command count followed by commands, or a compact sequence described in the statement."
    return "Integers describing sizes or limits, followed by the list values described in the statement."


def _output_format(problem: dict[str, Any]) -> str:
    topics = set(problem["required_topics"])
    if "conditions" in topics and problem["difficulty"] == "Beginner":
        return "Print the requested label or computed value."
    if "graphs" in topics:
        return "Print the requested connectivity, distance, path, or count result."
    if "dynamic_programming" in topics:
        return "Print the optimal value or number of ways."
    return "Print the requested answer in the format shown by the sample."


def _hints(problem: dict[str, Any]) -> list[str]:
    required = problem["required_topics"]
    hints = [
        f"Start by identifying where {display_name(required[0]).lower()} appears in the input.",
    ]
    if "hash_maps" in required:
        hints.append("Use a map when the problem asks for fast lookup or frequency counts.")
    if "sliding_window" in required:
        hints.append("Keep a window with left and right indexes instead of restarting each range.")
    if "dynamic_programming" in required:
        hints.append("Define the state before writing transitions; check smaller examples by hand.")
    if "graphs" in required:
        hints.append("Build an adjacency structure before choosing BFS, DFS, or a priority queue.")
    if "binary_search" in required:
        hints.append("Look for a sorted range or a monotonic yes/no answer.")
    if len(hints) == 1:
        hints.append("Write down the input size and decide whether a single scan is enough.")
    return hints[:3]


def _statement(problem: dict[str, Any]) -> str:
    topics = ", ".join(display_name(topic).lower() for topic in problem["required_topics"])
    if problem["difficulty"] in {"Medium", "Hard"}:
        scale = "The input can be large, so an efficient approach and time complexity reasoning matter."
    elif problem["difficulty"] == "Easy":
        scale = "The input is moderate, but avoid unnecessary nested loops when a direct structure is available."
    else:
        scale = "The input is small and is designed for careful practice with the basics."
    return (
        f"{problem['focus']} The main concepts are {topics}. {scale} "
        "Return exactly the requested result; do not print extra explanation."
    )


def build_problem_database() -> list[dict[str, Any]]:
    problems: list[dict[str, Any]] = []
    for problem in _expanded_blueprints():
        enriched = {
            **problem,
            "statement": _statement(problem),
            "input_format": _input_format(problem),
            "output_format": _output_format(problem),
            "estimated_time": DIFFICULTY_TIME[problem["difficulty"]],
            "tags": sorted(set(problem["required_topics"] + problem["prerequisite_topics"])),
            "hints": _hints(problem),
            "explanation_summary": (
                "A good solution centers on "
                + ", ".join(display_name(topic) for topic in problem["required_topics"])
                + "."
            ),
            "evaluation": True,
        }
        problems.append(enriched)

    counts = Counter(problem["difficulty"] for problem in problems)
    if counts != TARGET_DIFFICULTY_COUNTS:
        raise ValueError(f"Problem distribution changed: {dict(counts)} != {TARGET_DIFFICULTY_COUNTS}")
    if len({problem["id"] for problem in problems}) != len(problems):
        raise ValueError("Problem ids must be unique.")
    return problems


PROBLEMS = build_problem_database()
PROBLEM_BY_ID = {problem["id"]: problem for problem in PROBLEMS}
